"""Generates the label table and the indexes from the WHATWG Encoding Standard.

Usage: python3 -I dev/generate.py WHATWG_ENCODING_CHECKOUT COMMIT

Writes, relative to the current directory:

- src/text_encoding/internal/labels.gleam: `name(label)`, the encoding name
  for a label that is already trimmed and ASCII-lowercased.
- src/text_encoding/internal/single_byte_index.gleam: `table(name)`, the
  index for each legacy single-byte encoding, 128 entries of 16 bits.
- src/text_encoding/internal/index_<name>.gleam: `code_point(pointer)` for
  each multi-byte index, 0 when the index has no entry for the pointer.
- src/text_encoding/internal/index_gb18030_ranges.gleam: the ranges, as
  32-bit pointer and code point pairs.
- test/fixtures/whatwg/labels.tsv: every label and its encoding's name.

Indexes are stored as BitArray constants built from string segments: UTF-16
(two bytes per entry) when every code point is in the Basic Multilingual
Plane, UTF-32 (four bytes) otherwise. U+0000 marks a missing entry; no index
maps a pointer to it.
"""

import json
import pathlib
import sys

HEADER = """//// Generated by dev/generate.py from the WHATWG Encoding Standard
//// (https://github.com/whatwg/encoding, commit {commit}). Do not edit.
////
//// Copyright (c) WHATWG (Apple, Google, Mozilla, Microsoft). Licensed under
//// the BSD 3-Clause License; see LICENSE-WHATWG.
"""

PER_LINE = 16


def escape(codepoint):
    assert not 0xD800 <= codepoint <= 0xDFFF, codepoint
    return "\\u{%X}" % codepoint


def segments(codepoints, unit):
    lines = []
    for start in range(0, len(codepoints), PER_LINE):
        chunk = codepoints[start : start + PER_LINE]
        lines.append('  "%s":%s,' % ("".join(escape(c) for c in chunk), unit))
    return "\n".join(lines)


def table(codepoints):
    """Returns the constant body and the lookup function name."""
    # U+0000 would read as a missing entry.
    assert 0 not in codepoints
    codepoints = [0 if c is None else c for c in codepoints]
    if max(codepoints) <= 0xFFFF:
        return "<<\n%s\n>>" % segments(codepoints, "utf16"), "lookup16"
    return "<<\n%s\n>>" % segments(codepoints, "utf32"), "lookup32"


def write(path, text):
    path = pathlib.Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def labels(encodings, commit):
    entries = []
    for group in encodings:
        for encoding in group["encodings"]:
            for label in encoding["labels"]:
                entries.append((label, encoding["name"]))
    assert len({label for label, _ in entries}) == len(entries)
    cases = "\n".join('    "%s" -> Ok("%s")' % entry for entry in sorted(entries))
    return (
        HEADER.format(commit=commit)
        + """
/// The name of the encoding with this label. The label must already have
/// had ASCII whitespace removed from both ends and be ASCII-lowercased.
pub fn name(label: String) -> Result(String, Nil) {
  case label {
%s
    _ -> Error(Nil)
  }
}
"""
        % cases
    )


def single_byte(encodings, indexes, commit):
    names = []
    for group in encodings:
        if group["heading"] == "Legacy single-byte encodings":
            names = [encoding["name"] for encoding in group["encodings"]]
    assert len(names) == 28, names
    constants = []
    cases = []
    for name in names:
        key = name.lower()
        # ISO-8859-8-I shares the index of ISO-8859-8.
        index = indexes["iso-8859-8" if key == "iso-8859-8-i" else key]
        assert len(index) == 128
        body, lookup = table(index)
        assert lookup == "lookup16"
        constant = key.replace("-", "_")
        if key != "iso-8859-8-i":
            constants.append("const %s = %s" % (constant, body))
        else:
            constant = "iso_8859_8"
        cases.append('    "%s" -> Ok(%s)' % (name, constant))
    return (
        HEADER.format(commit=commit)
        + """
/// The index of a legacy single-byte encoding, by name: 128 entries of 16
/// bits for the bytes 0x80 to 0xFF, 0 when there is no entry.
pub fn table(name: String) -> Result(BitArray, Nil) {
  case name {
%s
    _ -> Error(Nil)
  }
}

%s
"""
        % ("\n".join(cases), "\n\n".join(constants))
    )


def multi_byte(name, index, commit):
    body, lookup = table(index)
    return (
        HEADER.format(commit=commit)
        + """
import text_encoding/internal/index

/// The index code point for a pointer in index %s, or 0 if the index has
/// no entry for it.
pub fn code_point(pointer: Int) -> Int {
  index.%s(data, pointer)
}

const data = %s
"""
        % (name, lookup, body)
    )


def ranges(index, commit):
    pairs = "\n".join("  %d:32, 0x%X:32," % (p, c) for p, c in index)
    return (
        HEADER.format(commit=commit)
        + """
/// Index gb18030 ranges, sorted by pointer: pairs of a 32-bit pointer and a
/// 32-bit code point.
pub const data = <<
%s
>>

pub const count = %d
"""
        % (pairs, len(index))
    )


def main():
    checkout, commit = pathlib.Path(sys.argv[1]), sys.argv[2]
    encodings = json.loads((checkout / "encodings.json").read_text())
    indexes = json.loads((checkout / "indexes.json").read_text())
    out = pathlib.Path("src/text_encoding/internal")
    write(out / "labels.gleam", labels(encodings, commit))
    write(out / "single_byte_index.gleam", single_byte(encodings, indexes, commit))
    for name in ["big5", "euc-kr", "gb18030", "jis0208", "jis0212"]:
        module = "index_" + name.replace("-", "_")
        write(out / (module + ".gleam"), multi_byte(name, indexes[name], commit))
    write(
        out / "index_gb18030_ranges.gleam",
        ranges(indexes["gb18030-ranges"], commit),
    )
    write("test/fixtures/whatwg/labels.tsv", label_fixture(encodings))


def label_fixture(encodings):
    """Every label and its encoding's name, for the tests."""
    rows = []
    for group in encodings:
        for encoding in group["encodings"]:
            for label in encoding["labels"]:
                rows.append("%s\t%s\n" % (label, encoding["name"]))
    return "".join(rows)


main()
